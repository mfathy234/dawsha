import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'
import { closeApp, createSandbox, launchApp } from './helpers'

test('pending Trash blocks edits and new tabs across Files hide/show and unlocks on failure', async () => {
  test.setTimeout(120_000)
  const sandbox = createSandbox()
  mkdirSync(join(sandbox.projectFolder, 'src'))
  writeFileSync(join(sandbox.projectFolder, 'src/a.txt'), 'original')
  writeFileSync(join(sandbox.projectFolder, 'src/b.txt'), 'second')
  const { app, page } = await launchApp(sandbox)
  const editor = page.locator('.files-editor:not([hidden]) .cm-content')
  try {
    await app.evaluate(({ ipcMain }) => {
      ipcMain.removeHandler('files:trash')
      ipcMain.handle('files:trash', () => new Promise(resolve => {
        ;(globalThis as unknown as { finishTestTrash: () => void }).finishTestTrash = () => resolve({ ok: false, error: 'Deferred Trash failure' })
      }))
    })
    await page.locator('#files-button').click()
    await page.locator('.files-row[data-path="src"]').click()
    await page.locator('.files-row[data-path="src/a.txt"]').click()
    await page.locator('#files-edit').click()
    await editor.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.type(' consented')
    await page.locator('.files-row[data-path="src"]').click({ button: 'right' })
    await page.getByRole('menuitem', { name: 'Delete…' }).click()
    await page.getByRole('button', { name: /^Discard changes and move/ }).click()
    await expect(page.locator('#files-view')).toHaveAttribute('inert', '')
    await expect(page.locator('#files-view')).toHaveAttribute('aria-busy', 'true')
    await editor.evaluate(element => (element as HTMLElement).focus())
    await page.keyboard.type(' UNSAFE LATE EDIT')
    await page.locator('.files-row[data-path="src/b.txt"]').click({ force: true })
    await expect(page.locator('.files-tab')).toHaveCount(1)
    await expect(editor).toHaveText('original consented')
    await page.locator('#sessions-button').click()
    await page.locator('#files-button').click()
    await expect(page.locator('#files-view')).toBeVisible()
    await expect(page.locator('#files-view')).toHaveAttribute('inert', '')
    await expect(editor).toHaveText('original consented')
    await app.evaluate(() => (globalThis as unknown as { finishTestTrash: () => void }).finishTestTrash())
    await expect(page.locator('#files-view')).not.toHaveAttribute('inert', '')
    await expect(page.locator('#files-view')).not.toHaveAttribute('aria-busy', 'true')
    await expect(page.locator('.toast').filter({ hasText: 'Deferred Trash failure' })).toBeVisible()
    await editor.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.type(' safely resumed')
    await expect(editor).toHaveText('original consented safely resumed')
    await page.locator('.files-tab-close').click()
    await page.getByRole('button', { name: /^Discard changes to/ }).click()
  } finally { await closeApp(app) }
})

test('checkout selection keeps dirty documents separate; Delete cancels safely and trashes confirmed descendants', async () => {
  test.setTimeout(120_000)
  const sandbox = createSandbox()
  const root = sandbox.projectFolder
  const git = (...args: string[]) => execFileSync('git', ['-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', ...args], { cwd: root, encoding: 'utf8' })
  git('init', '-q', '-b', 'main')
  mkdirSync(join(root, 'src'))
  writeFileSync(join(root, 'src/a.txt'), 'main checkout')
  git('add', '.')
  git('commit', '-qm', 'initial')
  const linked = join(sandbox.root, 'linked')
  git('worktree', 'add', '-qb', 'review', linked)
  writeFileSync(join(linked, 'src/a.txt'), 'linked checkout')
  const { app, page } = await launchApp(sandbox)
  const editor = page.locator('.files-editor:not([hidden]) .cm-content')
  const row = (path: string) => page.locator(`.files-row[data-path="${path}"]`)
  const select = async (folder: string) => page.locator('#files-checkout').evaluate((element, value) => {
    const select = element as HTMLSelectElement
    select.value = value
    select.dispatchEvent(new Event('change', { bubbles: true }))
  }, folder)
  try {
    await page.locator('#files-button').click()
    await expect(page.locator('#files-checkout option')).toHaveCount(2)
    await row('src').click()
    await row('src/a.txt').click()
    await expect(editor).toHaveText('main checkout')
    await page.locator('#files-edit').click()
    await editor.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.type(' unsaved')
    await select(linked)
    await row('src').click()
    await row('src/a.txt').click()
    await expect(editor).toHaveText('linked checkout')
    await select(root)
    await expect(editor).toHaveText('main checkout unsaved')
    await row('src').click({ button: 'right' })
    await page.getByRole('menuitem', { name: 'Delete…' }).click()
    const dialog = page.getByRole('alertdialog')
    await expect(dialog).toContainText('src/a.txt')
    await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(editor).toHaveText('main checkout unsaved')
    expect(existsSync(join(root, 'src/a.txt'))).toBe(true)
    const rejected = await page.evaluate(async folder => {
      const api = window.gridApi
      return Promise.all(['', '../outside', '.git', '.git/config'].map(path => api.trashProjectPath(folder, path)))
    }, root)
    expect(rejected.every(result => !result.ok)).toBe(true)
    await row('src').click({ button: 'right' })
    await page.getByRole('menuitem', { name: 'Delete…' }).click()
    await page.getByRole('button', { name: /^Discard changes and move/ }).click()
    await expect.poll(() => existsSync(join(root, 'src'))).toBe(false)
    await expect(page.locator('.files-tab')).toHaveCount(0)
    await expect(row('src/a.txt').locator('.files-badge')).toHaveText('D')
    expect(existsSync(join(linked, 'src/a.txt'))).toBe(true)
    await select(linked)
    await expect(editor).toHaveText('linked checkout')
  } finally { await closeApp(app) }
})
