import { describe, expect, it } from 'vitest'
import { claudeDetail } from '../../src/shared/sessionDetail'
import { clipWords, flattenText, isAutomaticSession, realPrompt, realReply } from '../../src/shared/sessionText'

const lines = (...records: unknown[]): string => records.map((r) => JSON.stringify(r)).join('\n')

describe('realPrompt', () => {
  it('drops harness-only messages', () => {
    for (const raw of [
      '<command-name>/login</command-name>\n  <command-message>login</command-message>\n  <command-args></command-args>',
      '<local-command-stdout>Login successful</local-command-stdout>',
      '<bash-input>git status</bash-input>',
      '<task-notification><task-id>abc</task-id></task-notification>',
      '[Request interrupted by user for tool use]',
      'Caveat: The messages below were generated by the user while running local commands.',
      'This session is being continued from a previous conversation that ran out of context.\n\nSummary:\n## What',
      'Base directory for this skill: C:/x/skills/demo\n\nWHERE TO WRITE IT',
      '<system-reminder>Plan mode is active</system-reminder>',
      '   '
    ]) expect(realPrompt(raw)).toBeNull()
  })

  it('keeps the typed request and drops what the harness wrapped around it', () => {
    expect(realPrompt('<system-reminder>ctx</system-reminder>Fix the login redirect')).toBe('Fix the login redirect')
    expect(realPrompt('[Image #1] how do i get the plan mode on the right side')).toBe('how do i get the plan mode on the right side')
    expect(realPrompt('<pasted_content id="aee1">\nPOST /auth 200\nPUT /auth 409\n</pasted_content>')).toBe('POST /auth 200 PUT /auth 409')
    expect(realPrompt('<command-name>/review</command-name><command-args>PR 12</command-args>')).toBe('/review PR 12')
  })

  it('labels automatic sessions instead of showing their boilerplate', () => {
    expect(realPrompt('Below is a conversation log from a Claude Code coding session. Create a summary to help')).toBe('Automatic summary of an earlier session')
    expect(realPrompt('The following is the Codex agent history whose request action you are assessing.')).toBe('Automatic safety review of a command')
  })

  it('removes ANSI, collapses pasted code and keeps Arabic intact', () => {
    expect(realPrompt('\u001b[31mfailing\u001b[0m build')).toBe('failing build')
    expect(realPrompt('why does this fail\n```ts\nconst a = 1\nconst b = 2\n```\nthanks')).toBe('why does this fail [code] thanks')
    expect(realPrompt('اصلح مشكلة تسجيل الدخول في الصفحة')).toBe('اصلح مشكلة تسجيل الدخول في الصفحة')
  })
})

describe('realReply', () => {
  it('turns markdown into plain readable text', () => {
    const raw = '## Session Summary\n\n**Tasks**\n- Pulled `main` and merged\n- See [the PR](https://x.test/pr/1)\n\n| a | b |\n|---|---|\n| 1 | 2 |'
    expect(realReply(raw)).toBe('Session Summary Tasks • Pulled main and merged • See the PR a · b 1 · 2')
  })

  it('skips replies with no words and cuts long ones at a word', () => {
    expect(realReply('```\n```')).toBeNull()
    expect(realReply('---')).toBeNull()
    const long = realReply('word '.repeat(300), 50) as string
    expect(long.endsWith('word…')).toBe(true)
    expect(long.length).toBeLessThanOrEqual(51)
  })
})

describe('clipWords', () => {
  it('leaves short text alone and never splits a surrogate pair', () => {
    expect(clipWords('short', 10)).toBe('short')
    const clipped = clipWords('a'.repeat(9) + '😀' + 'b'.repeat(20), 10)
    expect(clipped).toBe('a'.repeat(9) + '…')
  })
})

describe('flattenText', () => {
  it('unwraps unclosed injected blocks', () => {
    expect(flattenText('<system-reminder>never closed and long')).toBe('')
  })
})

describe('claudeDetail with real-looking sessions', () => {
  it('picks the first real request and the last real reply', () => {
    const text = lines(
      { type: 'user', message: { content: '<command-name>/clear</command-name>' } },
      { type: 'user', message: { content: '<local-command-stdout></local-command-stdout>' } },
      { type: 'user', message: { content: [{ type: 'text', text: '[Image #1] the sidebar is cut off' }] } },
      { type: 'assistant', isSidechain: true, message: { model: 'claude-opus-5-5', content: [{ type: 'text', text: 'sub-agent chatter' }] } },
      { type: 'assistant', message: { model: 'claude-opus-5-5', content: [{ type: 'text', text: 'I widened the **sidebar** minimum.' }] } },
      { type: 'assistant', message: { model: '<synthetic>', content: [{ type: 'text', text: 'No response requested.' }] } },
      { type: 'assistant', message: { model: 'claude-opus-5-5', content: [{ type: 'tool_use', name: 'Edit' }] } }
    )
    const detail = claudeDetail(text)
    expect(detail.firstPrompt).toBe('the sidebar is cut off')
    expect(detail.lastAssistant).toBe('I widened the sidebar minimum.')
    expect(detail.messages).toBe(3)
  })
})

describe('automatic sessions', () => {
  it('recognises the labels given to sessions other tools started', () => {
    expect(isAutomaticSession(realPrompt('Below is a conversation log from a Claude Code coding session. Create a summary.') ?? undefined)).toBe(true)
    expect(isAutomaticSession(realPrompt('The following is the Codex agent history whose request action you are assessing') ?? undefined)).toBe(true)
    expect(isAutomaticSession('Add dark mode toggle')).toBe(false)
    expect(isAutomaticSession(undefined)).toBe(false)
  })
})
